use inflector::Inflector;
use serde::Deserialize;
use std::{collections::HashSet, env, fs};

#[derive(Debug, Deserialize)]
struct MethodInfo {
    name: String,
    desc: String,
}

#[derive(Debug, Deserialize)]
struct ClassInfo {
    #[serde(rename = "className")]
    class_name: String,
    constructors: Vec<MethodInfo>,
    methods: Vec<MethodInfo>,
}

// Maps JVM types to Rust jni types and JValue conversions
fn jvm_to_rust(jvm: &str) -> (&'static str, &'static str) {
    match jvm {
        "V" => ("()", ""),
        "Z" => ("jboolean", ".z().unwrap()"),
        "B" => ("jbyte", ".b().unwrap()"),
        "C" => ("jchar", ".c().unwrap()"),
        "S" => ("jshort", ".s().unwrap()"),
        "I" => ("jint", ".i().unwrap()"),
        "J" => ("jlong", ".j().unwrap()"),
        "F" => ("jfloat", ".f().unwrap()"),
        "D" => ("jdouble", ".d().unwrap()"),
        s if s.starts_with("L") => ("JObject<'a>", ".l().unwrap()"),
        s if s.starts_with("[") => ("JObject<'a>", ".l().unwrap()"),
        _ => ("JObject<'a>", ".l().unwrap()"),
    }
}

// Parses a JVM method descriptor into argument types and return type
fn parse_jvm_method_desc(desc: &str) -> (Vec<String>, String) {
    let mut chars = desc.chars().peekable();
    assert_eq!(chars.next(), Some('('));
    let mut args = Vec::new();
    while let Some(&c) = chars.peek() {
        if c == ')' {
            chars.next();
            break;
        }
        args.push(parse_jvm_type(&mut chars));
    }
    let ret = parse_jvm_type(&mut chars);
    (args, ret)
}

fn parse_jvm_type<I: Iterator<Item = char>>(chars: &mut std::iter::Peekable<I>) -> String {
    match chars.next() {
        Some('B') => "B".to_string(),
        Some('C') => "C".to_string(),
        Some('D') => "D".to_string(),
        Some('F') => "F".to_string(),
        Some('I') => "I".to_string(),
        Some('J') => "J".to_string(),
        Some('S') => "S".to_string(),
        Some('Z') => "Z".to_string(),
        Some('V') => "V".to_string(),
        Some('L') => {
            let mut typ = String::new();
            for c in chars.by_ref() {
                if c == ';' {
                    break;
                }
                typ.push(c);
            }
            format!("L{}", typ)
        }
        Some('[') => {
            let inner = parse_jvm_type(chars);
            format!("[{}", inner)
        }
        Some(c) => format!("Unknown({})", c),
        None => "Unknown(None)".to_string(),
    }
}

fn rust_names(java_class: &str) -> (String, String) {
    let parts: Vec<&str> = java_class.split('.').collect();
    let module = if parts.len() > 1 {
        parts[..parts.len() - 1].join("_")
    } else {
        "android".to_string()
    };
    let struct_name = parts.last().unwrap().to_pascal_case();
    (module, struct_name)
}

// JValue::from for primitives vs. objects (needs ref for objects/arrays)
fn make_jvalue(arg: &str, i: usize) -> String {
    match arg {
        "B" | "C" | "D" | "F" | "I" | "J" | "S" | "Z" => format!("JValue::from(arg{})", i),
        _ => format!("JValue::from(&arg{})", i), // JObject and arrays need &
    }
}

// Combine argument types for method overload suffixes
fn overload_suffix(args: &[String]) -> String {
    if args.is_empty() {
        return "".to_string();
    }
    let suffix = args
        .iter()
        .map(|t| {
            let (ty, _) = jvm_to_rust(t);
            // Strip lifetime for suffix
            ty.replace("<'a>", "").to_lowercase()
        })
        .collect::<Vec<_>>()
        .join("_");
    format!("_{}", suffix)
}

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() < 2 {
        eprintln!("Usage: {} <input-json>", args[0]);
        std::process::exit(1);
    }
    let json_str = fs::read_to_string(&args[1]).expect("Failed to read JSON file");
    let classes: serde_json::Value = serde_json::from_str(&json_str).expect("Failed to parse JSON");

    println!("#![allow(clippy::all)]");
    println!("// AUTOGENERATED JNI BINDINGS");
    println!("use jni::objects::*;");
    println!("use jni::sys::*;");
    println!("use jni::JNIEnv;");

    // Track which modules have been emitted to prevent duplicates
    let mut emitted_modules: HashSet<String> = HashSet::new();

    for (_java_class, value) in classes.as_object().unwrap() {
        let class_info: ClassInfo = serde_json::from_value(value.clone()).unwrap();
        let (module, struct_name) = rust_names(&class_info.class_name);

        // Only emit each module once
        if emitted_modules.contains(&module) {
            continue;
        }
        emitted_modules.insert(module.clone());

        println!();
        println!("pub mod {} {{", module);
        println!("    use super::*;");

        println!("    pub struct {}<'a> {{", struct_name);
        println!("        pub obj: JObject<'a>,");
        println!("    }}");

        println!("    impl<'a> {}<'a> {{", struct_name);

        // Constructors
        use std::collections::HashMap;
        let mut ctor_counts: HashMap<String, usize> = HashMap::new();
        for ctor in &class_info.constructors {
            let (args, _ret) = parse_jvm_method_desc(&ctor.desc);

            let args_str = args
                .iter()
                .enumerate()
                .map(|(i, t)| {
                    let (ty, _) = jvm_to_rust(t);
                    format!("arg{}: {}", i, ty)
                })
                .collect::<Vec<_>>()
                .join(", ");

            let jvalues = args
                .iter()
                .enumerate()
                .map(|(i, t)| make_jvalue(t, i))
                .collect::<Vec<_>>()
                .join(", ");

            let suffix = overload_suffix(&args);
            let count = ctor_counts.entry(suffix.clone()).or_insert(0);

            let fn_name = if *count == 0 {
                format!("new{}", suffix)
            } else {
                format!("new{}_{count}", suffix)
            };
            *count += 1;

            println!(
                "        pub fn {}(env: &mut JNIEnv<'a>, {}) -> {}<'a> {{",
                fn_name, args_str, struct_name
            );
            println!(
                "            let class = env.find_class(\"{}\").unwrap();",
                class_info.class_name.replace('.', "/")
            );
            println!(
                "            let obj = env.new_object(class, \"{}\", &[{}]).unwrap();",
                ctor.desc, jvalues
            );
            println!("            {} {{ obj }}", struct_name);
            println!("        }}");
        }

        // Methods
        let mut method_counts: HashMap<String, usize> = HashMap::new();
        for method in &class_info.methods {
            let base_name = method.name.to_snake_case();
            let (args, ret) = parse_jvm_method_desc(&method.desc);

            let args_str = args
                .iter()
                .enumerate()
                .map(|(i, t)| {
                    let (ty, _) = jvm_to_rust(t);
                    format!("arg{}: {}", i, ty)
                })
                .collect::<Vec<_>>()
                .join(", ");

            let jvalues = args
                .iter()
                .enumerate()
                .map(|(i, t)| make_jvalue(t, i))
                .collect::<Vec<_>>()
                .join(", ");

            let (ret_type, conv) = jvm_to_rust(&ret);

            let suffix = overload_suffix(&args);
            let count = method_counts
                .entry(format!("{}{}", base_name, suffix))
                .or_insert(0);

            let fn_name = if *count == 0 {
                format!("{}{}", base_name, suffix)
            } else {
                format!("{}{}_{count}", base_name, suffix)
            };
            *count += 1;

            // If returning JObject, use correct lifetime
            let ret_decl = if ret_type == "JObject<'a>" {
                "JObject<'a>"
            } else {
                ret_type
            };

            println!(
                "        pub fn {}(&self, env: &mut JNIEnv<'a>, {}) -> {} {{",
                fn_name, args_str, ret_decl
            );

            if ret_type == "()" {
                println!(
                    "            env.call_method(&self.obj, \"{}\", \"{}\", &[{}]).unwrap();",
                    method.name, method.desc, jvalues
                );
            } else if ret_type == "JObject<'a>" {
                println!(
                    "            env.call_method(&self.obj, \"{}\", \"{}\", &[{}]).unwrap().l().unwrap()",
                    method.name, method.desc, jvalues
                );
            } else if ret_type == "jboolean" {
                println!(
                    "            (env.call_method(&self.obj, \"{}\", \"{}\", &[{}]).unwrap().z().unwrap()) as jboolean",
                    method.name, method.desc, jvalues
                );
            } else {
                println!(
                    "            env.call_method(&self.obj, \"{}\", \"{}\", &[{}]).unwrap(){}",
                    method.name, method.desc, jvalues, conv
                );
            }
            println!("        }}");
        }

        println!("    }}");
        println!("}}");
    }
}
